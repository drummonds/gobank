// Package family maps the gobank family: the modules of our own that a
// build of the Model Bank selects, and what each asks of the others. It
// is read from `go mod graph` and `go list -m all`, so the map is the
// build's, never drawn by hand, and a go.mod that asks for an older
// version than the build selects shows as a lag.
package family

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// hosts are the module path prefixes that make a module one of ours.
var hosts = []string{"git.bytestone.uk/hum3/", "github.com/drummonds/", "codeberg.org/hum3/"}

// Repo is one of our repositories: all its modules as one node, with the
// version the build selected (empty for the main module's own repo).
type Repo struct {
	Name, Version string
}

// Requirement is what one repo's go.mod asks of another: the version
// named there, which is not always the one the build selects.
type Requirement struct {
	From, To, Version string
}

// Map is the family as one build sees it.
type Map struct {
	Repos    []Repo        // the main module's repo first, then by name
	Requires []Requirement // sorted by From, To, Version
}

// repoOf is the repo a module path belongs to, or "" for a third party.
func repoOf(module string) string {
	for _, h := range hosts {
		if rest, ok := strings.CutPrefix(module, h); ok {
			name, _, _ := strings.Cut(rest, "/")
			return name
		}
	}
	return ""
}

// Parse reads `go mod graph` (dependent dependency@version per line) and
// `go list -m all` (module version per line, the main module without one).
func Parse(graph, buildList string) (Map, error) {
	selected := map[string]string{}
	var main string
	for line := range strings.SplitSeq(strings.TrimSpace(buildList), "\n") {
		f := strings.Fields(line)
		if len(f) == 0 {
			continue
		}
		name := repoOf(f[0])
		if name == "" {
			continue
		}
		if len(f) == 1 {
			main, selected[name] = name, ""
			continue
		}
		if name == main {
			continue // the main module's repo replaced by itself
		}
		if _, seen := selected[name]; !seen || compare(f[1], selected[name]) > 0 {
			selected[name] = f[1]
		}
	}
	if main == "" {
		return Map{}, fmt.Errorf("family: no main module in the build list")
	}
	seen := map[Requirement]bool{}
	var m Map
	for line := range strings.SplitSeq(strings.TrimSpace(graph), "\n") {
		f := strings.Fields(line)
		if len(f) != 2 {
			continue
		}
		fromPath, _, _ := strings.Cut(f[0], "@")
		toPath, version, _ := strings.Cut(f[1], "@")
		from, to := repoOf(fromPath), repoOf(toPath)
		if from == "" || to == "" || from == to {
			continue
		}
		if _, inBuild := selected[to]; !inBuild {
			continue
		}
		r := Requirement{From: from, To: to, Version: version}
		if !seen[r] {
			seen[r] = true
			m.Requires = append(m.Requires, r)
		}
	}
	sort.Slice(m.Requires, func(i, j int) bool {
		a, b := m.Requires[i], m.Requires[j]
		return a.From < b.From || a.From == b.From && (a.To < b.To || a.To == b.To && a.Version < b.Version)
	})
	for name, v := range selected {
		m.Repos = append(m.Repos, Repo{Name: name, Version: v})
	}
	sort.Slice(m.Repos, func(i, j int) bool {
		a, b := m.Repos[i], m.Repos[j]
		if (a.Name == main) != (b.Name == main) {
			return a.Name == main
		}
		return a.Name < b.Name
	})
	return m, nil
}

// Lags says whether a requirement asks for an older version than the
// build selected for that repo.
func (m Map) Lags(r Requirement) bool {
	for _, repo := range m.Repos {
		if repo.Name == r.To {
			return repo.Version != "" && compare(r.Version, repo.Version) < 0
		}
	}
	return false
}

// compare orders two versions of the form vMAJOR.MINOR.PATCH[-pre]; a
// pseudo-version or anything else falls back to string order.
func compare(a, b string) int {
	pa, pb := numbers(a), numbers(b)
	if pa == nil || pb == nil {
		return strings.Compare(a, b)
	}
	for i := range 3 {
		if pa[i] != pb[i] {
			if pa[i] < pb[i] {
				return -1
			}
			return 1
		}
	}
	return strings.Compare(a, b)
}

func numbers(v string) []int {
	v, _, _ = strings.Cut(strings.TrimPrefix(v, "v"), "-")
	parts := strings.Split(v, ".")
	if len(parts) != 3 {
		return nil
	}
	n := make([]int, 3)
	for i, p := range parts {
		x, err := strconv.Atoi(p)
		if err != nil {
			return nil
		}
		n[i] = x
	}
	return n
}

// D2 draws the map: one node per repo with its selected version, the
// root to the left and leaves to the right, and one edge per requirement.
// A lagging requirement is dashed and labelled with the version it asks
// for, so the go.mod to bring up to date can be read off the diagram.
func (m Map) D2() string {
	var sb strings.Builder
	sb.WriteString("# Generated by cmd/gendocs from go mod graph — do not edit\n")
	sb.WriteString("direction: right\n")
	sb.WriteString("classes: {\n  lags: {style.stroke: \"#c77400\"; style.stroke-dash: 4; style.font-color: \"#c77400\"}\n}\n\n")
	for _, r := range m.Repos {
		label := r.Name
		if r.Version != "" {
			label += " " + r.Version
		}
		fmt.Fprintf(&sb, "%s: %s\n", key(r.Name), strconv.Quote(label))
	}
	sb.WriteString("\n")
	for _, e := range m.Requires {
		if m.Lags(e) {
			fmt.Fprintf(&sb, "%s -> %s: %s {class: lags}\n", key(e.From), key(e.To), strconv.Quote(e.Version))
			continue
		}
		fmt.Fprintf(&sb, "%s -> %s\n", key(e.From), key(e.To))
	}
	return sb.String()
}

// key is a repo name as a d2 identifier.
func key(name string) string { return strings.ReplaceAll(name, "-", "_") }
